"""
run_sft.py  —  Supervised Fine-Tuning for the UE resource manager
-----------------------------------------------------------------
Trains SmolLM2-135M on the two-output dataset generated by
generate_dataset.py, teaching the model to produce:

  offload_decision   {true, false}   — offload to MEC or execute locally
  escalation_flag    {true, false}   — seek network LLM or act locally

Checkpoint evaluation
─────────────────────
After training completes, this script sweeps every saved checkpoint,
merges the LoRA adapter into the base weights for each one, runs a
lightweight evaluation using evaluate.py, and writes a per-checkpoint
results file:

  models/sft_checkpoint_eval.json

  Format: list of dicts, one per checkpoint, each containing:
    {
      "checkpoint":    "models/sft-ue-baseline/checkpoint-50",
      "step":          50,
      "cvr_c1":        0.04,
      "cvr_c8":        0.02,
      "cvr_combined":  0.03,
      "id_accuracy":   0.61,
      "ood_accuracy":  0.38,
      "ood_gap":       0.23,
      "mnu":           0.18,
      "parse_fail":    0.01
    }

  This lets you pick the best SFT checkpoint to use as the GRPO
  starting point rather than always taking the final epoch.

Checkpoint saving
─────────────────
  save_strategy = "steps"
  save_steps    = 50     →  one checkpoint per ~50 gradient steps

  With ~950 augmented samples, batch=1, grad_accum=4:
    steps_per_epoch ≈ 950 / 4 = 237 steps
    total_steps     ≈ 237 × 5 = 1187 steps
    checkpoints     ≈ 1187 / 50 ≈ 23 checkpoints
    + 5 end-of-epoch saves = ~28 checkpoints total

  save_total_limit = 30  keeps all of them.

Two-output schema
─────────────────
  Primary outputs:  offload_decision, escalation_flag
  Diagnostic fields (burn_rate_gflops_s, c1_active, c8_active,
  offload_feasible, escalation_reason) are stripped from the training
  text — the model only learns to produce the two primary outputs.

Prompt format  (identical to run_grpo.py and evaluate.py)
──────────────────────────────────────────────────────────
  UE Context: <state including energy credit>
  Required keys (offload_decision, escalation_flag):
  Decision:
  {"offload_decision": <bool>, "escalation_flag": <bool>}<|endoftext|>

Stratified oversampling
───────────────────────
  2× oversampling on: c1_only, c8_only, c1_and_c8, low_confidence_proxy
  No oversampling on: general, esc_zone, boundary, mobility strata

Usage
─────
  python scripts/run_sft.py
  python scripts/run_sft.py --no-eval      # skip checkpoint evaluation
  python scripts/run_sft.py --eval-only    # only run evaluation on existing checkpoints
"""

import os
import sys
import glob
import json
import argparse
import torch
from datasets import load_dataset, concatenate_datasets
from transformers import AutoModelForCausalLM, AutoTokenizer
from peft import LoraConfig, PeftModel
from trl import SFTTrainer, SFTConfig

# ── Paths ──────────────────────────────────────────────────────────────────────
SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
ROOT         = os.path.normpath(os.path.join(SCRIPT_DIR, ".."))
MODEL_ID     = "HuggingFaceTB/SmolLM2-135M"
DATA_FILE    = os.path.join(ROOT, "data",   "train_data.jsonl")
OUTPUT_DIR   = os.path.join(ROOT, "models", "sft-ue-baseline")
MERGED_DIR   = os.path.join(ROOT, "models", "sft-ue-merged")
CKPT_EVAL    = os.path.join(ROOT, "models", "sft_checkpoint_eval.json")

sys.path.insert(0, ROOT)

# Primary output keys — diagnostic fields are stripped from training text
PRIMARY_OUTPUT_KEYS = {"offload_decision", "escalation_flag"}


# ═══════════════════════════════════════════════════════════════════════════════
# 1.  Prompt formatter
# ═══════════════════════════════════════════════════════════════════════════════

def format_example(example):
    """
    Assemble the full training text from a (prompt, response) pair.

    Diagnostic fields in the response JSON are stripped so the model
    only learns to generate the two primary output fields.  The prompt
    format is kept identical to run_grpo.py and evaluate.py so the
    model never sees an out-of-distribution prefix at inference time.
    """
    full_response  = json.loads(example["response"])
    clean_response = {
        k: v for k, v in full_response.items()
        if k in PRIMARY_OUTPUT_KEYS
    }
    example["text"] = (
        f"UE Context: {example['prompt']}\n"
        f"Required keys (offload_decision, escalation_flag):\n"
        f"Decision:\n"
        f"{json.dumps(clean_response)}<|endoftext|>"
    )
    return example


# ═══════════════════════════════════════════════════════════════════════════════
# 2.  Stratum filters for oversampling
# ═══════════════════════════════════════════════════════════════════════════════

def is_c1(example):
    r = json.loads(example["response"])
    return r.get("c1_active", False) and not r.get("c8_active", False)

def is_c8(example):
    r = json.loads(example["response"])
    return r.get("c8_active", False) and not r.get("c1_active", False)

def is_c1_and_c8(example):
    r = json.loads(example["response"])
    return r.get("c1_active", False) and r.get("c8_active", False)

def is_low_confidence_proxy(example):
    return (example.get("meta") or {}).get("stratum") == "low_confidence_proxy"


# ═══════════════════════════════════════════════════════════════════════════════
# 3.  Dataset loading and stratified oversampling
# ═══════════════════════════════════════════════════════════════════════════════

def load_and_augment(data_file):
    """
    Load the dataset and oversample hard-constraint and ambiguity groups
    at 2× so the model sees enough of each constraint region.

    Oversampled 2×: c1_only, c8_only, c1_and_c8, low_confidence_proxy
    Not oversampled: general, esc_zone, boundary, mobility strata
    """
    print("Loading dataset …")
    raw = load_dataset("json", data_files=data_file, split="train")
    n   = len(raw)

    c1_set  = raw.filter(is_c1)
    c8_set  = raw.filter(is_c8)
    c18_set = raw.filter(is_c1_and_c8)
    lcp_set = raw.filter(is_low_confidence_proxy)

    print(f"  Base                      : {n}")
    print(f"  C1 only                   : {len(c1_set)}  ({100*len(c1_set)/n:.0f}%)")
    print(f"  C8 only                   : {len(c8_set)}  ({100*len(c8_set)/n:.0f}%)")
    print(f"  C1 ∩ C8                   : {len(c18_set)}  ({100*len(c18_set)/n:.0f}%)")
    print(f"  Low-confidence proxy      : {len(lcp_set)}  ({100*len(lcp_set)/n:.0f}%)")

    augmented = concatenate_datasets([
        raw, c1_set, c8_set, c18_set, lcp_set
    ]).shuffle(seed=42)

    print(f"  Augmented total           : {len(augmented)}")
    return augmented


# ═══════════════════════════════════════════════════════════════════════════════
# 4.  Checkpoint utilities
# ═══════════════════════════════════════════════════════════════════════════════

def list_checkpoints(output_dir):
    """
    Return all checkpoint directories sorted by step number (ascending).
    Includes both step-based and epoch-based saves.
    """
    pattern   = os.path.join(output_dir, "checkpoint-*")
    ckpt_dirs = glob.glob(pattern)

    def step_of(path):
        try:
            return int(os.path.basename(path).split("-")[-1])
        except ValueError:
            return -1

    return sorted(
        [d for d in ckpt_dirs if step_of(d) >= 0],
        key=step_of
    )


def merge_checkpoint(base_model_id, ckpt_path, tokenizer):
    """
    Load the LoRA adapter at ckpt_path, merge it into the base model,
    and return the merged model in eval mode.

    The merged model is kept in memory for evaluation and discarded
    afterwards — it is never saved to disk during the checkpoint sweep.
    """
    base = AutoModelForCausalLM.from_pretrained(
        base_model_id,
        torch_dtype=torch.float32,
        device_map={"": "cpu"},
    )
    peft_model  = PeftModel.from_pretrained(base, ckpt_path)
    merged      = peft_model.merge_and_unload()
    merged.eval()
    return merged


# ═══════════════════════════════════════════════════════════════════════════════
# 5.  Lightweight evaluator
# ═══════════════════════════════════════════════════════════════════════════════

def run_checkpoint_eval(merged_model, tokenizer, ev, test_sets):
    """
    Run a lightweight evaluation on a single merged checkpoint.

    Uses the pre-built test sets from evaluate.py to avoid rebuilding
    them for every checkpoint.  Only runs the random baseline once
    (passed in via test_sets["random_results"]) and reuses it across
    all checkpoints to save time.

    Returns a flat dict of scalar metrics.
    """
    def get_pred(prompt):
        return ev.generate_config(merged_model, tokenizer, prompt)

    id_set       = test_sets["id_set"]
    c1_set       = test_sets["c1_set"]
    c8_set       = test_sets["c8_set"]
    combined_set = test_sets["combined_set"]
    credit_set   = test_sets["credit_set"]
    ood_set      = test_sets["ood_set"]
    mob_set      = test_sets["mob_set"]

    result = ev.evaluate_baseline(
        name         = "_ckpt_",
        get_pred_fn  = get_pred,
        id_set       = id_set,
        c1_set       = c1_set,
        c8_set       = c8_set,
        combined_set = combined_set,
        credit_set   = credit_set,
        ood_set      = ood_set,
        mobility_set = mob_set,
        quiet        = True,
    )

    return {
        # Family 1 — constraint safety
        "cvr_c1":       result["cvr_c1"],
        "cvr_c8":       result["cvr_c8"],
        "cvr_credit":   result["cvr_credit"],
        "cvr_combined": result["cvr_combined"],
        # Family 2 — offload quality (feasible region)
        "cor":          result["cor"],          # correct offload rate
        "offload_prec": result["offload_prec"], # offload precision
        "offload_rec":  result["offload_rec"],  # offload recall
        "offload_f1":   result["offload_f1"],   # offload F1
        # Family 3 — escalation quality
        "ver":          result["ver"],
        "er":           result["er"],
        "mer_ho":       result["mer_ho"],
        "esc_f1":       result["esc_f1"],
        # Family 4 — utility
        "mnu":          result["mnu"],
        "ccr":          result["ccr"],          # credit conservation ratio
        "parse_fail":   result["parse_fail"],
        # generalisation
        "id_accuracy":  result["id_accuracy"],
        "ood_accuracy": result["ood_accuracy"],
        "ood_gap":      result["ood_gap"],
    }


def sweep_checkpoints(output_dir, tokenizer, quiet=False):
    """
    Sweep every saved checkpoint in output_dir, evaluate each one,
    and write results to sft_checkpoint_eval.json.

    Strategy:
      1. Import evaluate.py and build test sets once.
      2. For each checkpoint (sorted by step):
           a. Merge the LoRA adapter into the base model (in memory).
           b. Run the lightweight evaluator.
           c. Append results to the records list.
           d. Delete the merged model to free memory before the next checkpoint.
      3. Write all records to CKPT_EVAL.
      4. Print a summary table showing the progression of key metrics
         across checkpoints so you can select the best one for GRPO.
    """
    checkpoints = list_checkpoints(output_dir)
    if not checkpoints:
        print("  [WARN] No checkpoints found — skipping evaluation sweep.")
        return

    print(f"\n{'='*64}")
    print(f"  SFT checkpoint evaluation sweep")
    print(f"  {len(checkpoints)} checkpoints found in {output_dir}")
    print(f"{'='*64}")

    # ── Import evaluate.py ────────────────────────────────────────────────────
    try:
        import importlib.util
        eval_path = os.path.normpath(os.path.join(SCRIPT_DIR, "evaluate.py"))
        spec      = importlib.util.spec_from_file_location("evaluate", eval_path)
        ev        = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(ev)
    except Exception as e:
        print(f"  [WARN] Could not import evaluate.py: {e}")
        print("         Skipping checkpoint evaluation sweep.")
        return

    # ── Build test sets once ──────────────────────────────────────────────────
    print("\n  Building test sets …")
    trace_path = os.path.join(ROOT, "data", "radio_parameters_moving_clean.csv")
    test_sets = {
        "id_set":       ev.build_id_test_set(n=100),     # lighter for speed
        "c1_set":       ev.build_c1_set(n=60),
        "c8_set":       ev.build_c8_set(n=60),
        "combined_set": ev.build_combined_constraint_set(),
        "credit_set":   ev.build_credit_floor_set(n=50),
        "ood_set":      ev.build_ood_test_set(),
        "mob_set":      ev.build_mobility_set(trace_path),
    }
    n_total_samples = sum(len(v) for v in test_sets.values())
    print(f"  Total eval samples per checkpoint: {n_total_samples}")

    # ── Sweep ─────────────────────────────────────────────────────────────────
    records = []
    header_printed = False

    for ckpt_path in checkpoints:
        step = int(os.path.basename(ckpt_path).split("-")[-1])

        if not quiet:
            print(f"\n  [{step:>5}] Merging {os.path.basename(ckpt_path)} …",
                  end="", flush=True)

        try:
            merged = merge_checkpoint(MODEL_ID, ckpt_path, tokenizer)
        except Exception as e:
            print(f"\n  [WARN] Could not merge {ckpt_path}: {e} — skipping.")
            continue

        try:
            metrics = run_checkpoint_eval(merged, tokenizer, ev, test_sets)
        except Exception as e:
            print(f"\n  [WARN] Eval failed at step {step}: {e} — skipping.")
            del merged
            continue

        del merged   # free memory before next checkpoint

        record = {"checkpoint": ckpt_path, "step": step, **metrics}
        records.append(record)

        # Print a one-line summary for this checkpoint
        if not header_printed:
            print(f"\n  {'Step':>6}  {'CVR':>6}  {'ID Acc':>7}"
                  f"  {'OOD Acc':>8}  {'COR':>6}  {'Off-P':>7}"
                  f"  {'Off-R':>7}  {'VER':>6}  {'ER':>6}"
                  f"  {'CCR':>6}  {'MNU':>8}")
            print("  " + "-" * 84)
            header_printed = True

        ccr_str = f"{metrics['ccr']:.1%}" if metrics['ccr'] is not None else "  n/a"
        print(
            f"  {step:>6}  "
            f"{metrics['cvr_combined']:>6.1%}  "
            f"{metrics['id_accuracy']:>7.1%}  "
            f"{metrics['ood_accuracy']:>8.1%}  "
            f"{metrics['cor']:>6.1%}  "
            f"{metrics['offload_prec']:>7.1%}  "
            f"{metrics['offload_rec']:>7.1%}  "
            f"{metrics['ver']:>6.1%}  "
            f"{metrics['er']:>6.1%}  "
            f"{ccr_str:>6}  "
            f"{metrics['mnu']:>+8.4f}"
        )

    # ── Write results ─────────────────────────────────────────────────────────
    os.makedirs(os.path.dirname(CKPT_EVAL), exist_ok=True)
    with open(CKPT_EVAL, "w", encoding="utf-8") as f:
        json.dump(records, f, indent=4)
    print(f"\n  Results → {CKPT_EVAL}")

    # ── Best checkpoint summary ───────────────────────────────────────────────
    if not records:
        return

    # Rank by multiple criteria
    safe    = [r for r in records if r["cvr_combined"] == 0.0]
    best_safety = min(records, key=lambda r: (r["cvr_combined"], -r["id_accuracy"]))
    best_acc    = max(records, key=lambda r: r["id_accuracy"])
    best_mnu    = max(records, key=lambda r: r["mnu"])
    best_cor    = max(safe,    key=lambda r: r["cor"])    if safe else best_acc
    best_ccr    = max(
        [r for r in records if r["ccr"] is not None],
        key=lambda r: r["ccr"]
    ) if any(r["ccr"] is not None for r in records) else best_acc

    print(f"\n  Best checkpoints:")
    print(f"    Lowest CVR        : step {best_safety['step']:>5}"
          f"  CVR={best_safety['cvr_combined']:.1%}"
          f"  ID={best_safety['id_accuracy']:.1%}"
          f"  COR={best_safety['cor']:.1%}")
    print(f"    Highest ID Acc    : step {best_acc['step']:>5}"
          f"  CVR={best_acc['cvr_combined']:.1%}"
          f"  ID={best_acc['id_accuracy']:.1%}"
          f"  COR={best_acc['cor']:.1%}")
    print(f"    Highest COR (safe): step {best_cor['step']:>5}"
          f"  CVR={best_cor['cvr_combined']:.1%}"
          f"  COR={best_cor['cor']:.1%}"
          f"  Off-P={best_cor['offload_prec']:.1%}"
          f"  Off-R={best_cor['offload_rec']:.1%}")
    print(f"    Highest CCR       : step {best_ccr['step']:>5}"
          f"  CCR={best_ccr['ccr']:.1%}" if best_ccr['ccr'] is not None
          else f"    Highest CCR       : n/a")
    print(f"    Highest MNU       : step {best_mnu['step']:>5}"
          f"  MNU={best_mnu['mnu']:+.4f}"
          f"  ID={best_mnu['id_accuracy']:.1%}")
    print(f"\n  Recommended for GRPO: "
          f"checkpoint-{best_safety['step']}  (lowest CVR, "
          f"COR={best_safety['cor']:.1%})")

    return records


# ═══════════════════════════════════════════════════════════════════════════════
# 6.  Main
# ═══════════════════════════════════════════════════════════════════════════════

def main(no_eval=False, eval_only=False):

    # ── Tokenizer (needed for both training and eval) ─────────────────────────
    print(f"Loading tokenizer from {MODEL_ID} …")
    tokenizer = AutoTokenizer.from_pretrained(MODEL_ID)
    tokenizer.pad_token    = tokenizer.eos_token
    tokenizer.pad_token_id = tokenizer.eos_token_id

    if not eval_only:
        # ── Dataset ───────────────────────────────────────────────────────────
        raw_augmented = load_and_augment(DATA_FILE)
        source_cols   = [c for c in raw_augmented.column_names if c != "text"]
        dataset       = raw_augmented.map(format_example,
                                          remove_columns=source_cols)

        # ── Model ─────────────────────────────────────────────────────────────
        print(f"\nLoading base model ({MODEL_ID}) …")
        model = AutoModelForCausalLM.from_pretrained(
            MODEL_ID,
            device_map={"": "cpu"},
            torch_dtype=torch.float32,
        )

        # ── LoRA ──────────────────────────────────────────────────────────────
        lora_config = LoraConfig(
            r=8,
            lora_alpha=16,
            target_modules=["q_proj", "k_proj", "v_proj", "o_proj"],
            lora_dropout=0.05,
            bias="none",
            task_type="CAUSAL_LM",
        )

        # ── Training config ───────────────────────────────────────────────────
        # save_strategy="steps" with save_steps=50 produces ~23 intermediate
        # checkpoints over the full training run (~1187 total steps),
        # giving fine-grained coverage for the post-training sweep.
        #
        # save_total_limit=30 retains all checkpoints across the run.
        # Each SmolLM2-135M LoRA checkpoint is ~20 MB (adapter only),
        # so 30 checkpoints ≈ 600 MB total.
        print("Configuring SFT training …")
        training_args = SFTConfig(
            output_dir=OUTPUT_DIR,
            learning_rate=1e-4,
            per_device_train_batch_size=1,
            gradient_accumulation_steps=4,
            num_train_epochs=5,
            max_length=320,
            logging_steps=10,
            # Checkpoint saving — step-based for fine-grained sweep
            save_strategy="steps",
            save_steps=50,
            save_total_limit=30,
            optim="adamw_torch",
            report_to="none",
            dataset_text_field="text",
            fp16=False,
            bf16=False,
        )

        # ── Trainer ───────────────────────────────────────────────────────────
        trainer = SFTTrainer(
            model=model,
            train_dataset=dataset,
            args=training_args,
            peft_config=lora_config,
        )

        n_total  = len(dataset)
        n_epochs = int(training_args.num_train_epochs)
        print(f"\nStarting SFT on CPU ({n_total} samples × {n_epochs} epochs) …")
        print(f"Checkpoints saved every 50 steps → {OUTPUT_DIR}")
        print("Approximate time: 30–50 minutes\n")
        trainer.train()

        # ── Save final adapter ────────────────────────────────────────────────
        print(f"\nSaving final LoRA adapter → {OUTPUT_DIR}")
        trainer.model.save_pretrained(OUTPUT_DIR)
        tokenizer.save_pretrained(OUTPUT_DIR)

        # ── Merge final adapter → sft-ue-merged ──────────────────────────────
        # The final merged model is saved for GRPO to use as its starting point.
        # Checkpoint merges during the sweep are done in-memory only.
        print(f"\nMerging final adapter → {MERGED_DIR}")
        base = AutoModelForCausalLM.from_pretrained(
            MODEL_ID, torch_dtype=torch.float32, device_map={"": "cpu"}
        )
        peft_model = PeftModel.from_pretrained(base, OUTPUT_DIR)
        merged     = peft_model.merge_and_unload()
        merged.save_pretrained(MERGED_DIR)
        tokenizer.save_pretrained(MERGED_DIR)
        del merged, peft_model, base
        print(f"Merged model saved → {MERGED_DIR}")

    # ── Checkpoint evaluation sweep ───────────────────────────────────────────
    if not no_eval:
        sweep_checkpoints(OUTPUT_DIR, tokenizer, quiet=False)
    else:
        print("\n[--no-eval] Skipping checkpoint evaluation sweep.")
        print(f"  Run manually: python scripts/run_sft.py --eval-only")

    print("\nSFT complete.")
    print(f"  Final model  : {MERGED_DIR}")
    print(f"  Checkpoint eval: {CKPT_EVAL}")
    print(f"  Next step    : python scripts/run_grpo.py")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="SFT training with per-checkpoint evaluation sweep"
    )
    parser.add_argument(
        "--no-eval", action="store_true",
        help="Skip the post-training checkpoint evaluation sweep."
    )
    parser.add_argument(
        "--eval-only", action="store_true",
        help="Skip training and only run the evaluation sweep on existing checkpoints."
    )
    args = parser.parse_args()

    if args.eval_only and args.no_eval:
        parser.error("--eval-only and --no-eval are mutually exclusive.")

    main(no_eval=args.no_eval, eval_only=args.eval_only)